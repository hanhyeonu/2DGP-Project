    def draw_original_background(self, camera):
        """기존 배경 그리기 (kyoten + grass)"""
        tiles_x = self.canvas_width // self.tile_size + 1
        tiles_y = self.grass_height // self.tile_size + 1

        if camera:
            # 카메라 적용: 타일 그리기
            for y in range(tiles_y):
                for x in range(tiles_x):
                    world_x = x * self.tile_size + self.tile_size // 2
                    world_y = y * self.tile_size + self.tile_size // 2
                    draw_x, draw_y = camera.apply(world_x, world_y)

                    self.grass_tile.draw(
                        draw_x, draw_y,
                        self.tile_size, self.tile_size
                    )

            # 교토 이미지
            center_x, center_y = camera.apply(self.canvas_width // 2, self.canvas_height // 2)
            self.kyoten_image.draw(center_x, center_y, self.canvas_width, self.canvas_height)
        else:
            # 카메라 없으면 기존 방식
            for y in range(tiles_y):
                for x in range(tiles_x):
                    self.grass_tile.draw(
                        x * self.tile_size + self.tile_size // 2,
                        y * self.tile_size + self.tile_size // 2,
                        self.tile_size,
                        self.tile_size
                    )

            self.kyoten_image.draw(self.canvas_width // 2, self.canvas_height // 2, self.canvas_width,
                                   self.canvas_height)

    def draw_tilemap(self, camera):
        """타일맵 그리기 (맵1, 2, 3)"""
        for y in range(self.TILES_Y):
            for x in range(self.TILES_X):
                tile_value = self.current_map[y][x]

                # 월드 좌표 계산 (왼쪽 하단 기준)
                world_x = x * self.SCALED_TILE_SIZE + self.SCALED_TILE_SIZE // 2
                world_y = y * self.SCALED_TILE_SIZE + self.SCALED_TILE_SIZE // 2

                # 카메라 적용
                if camera:
                    draw_x, draw_y = camera.apply(world_x, world_y)
                else:
                    draw_x, draw_y = world_x, world_y

                # 타일 그리기
                if self.current_map_number == 1:
                    # 맵1: ground1 + wall1
                    if tile_value == 0:
                        self.tile_images['ground1'].draw(draw_x, draw_y, self.SCALED_TILE_SIZE, self.SCALED_TILE_SIZE)
                    elif tile_value == 1:
                        self.tile_images['wall1'].draw(draw_x, draw_y, self.SCALED_TILE_SIZE, self.SCALED_TILE_SIZE)

                elif self.current_map_number == 2:
                    # 맵2: ground2 + wall2
                    if tile_value == 0:
                        self.tile_images['ground2'].draw(draw_x, draw_y, self.SCALED_TILE_SIZE, self.SCALED_TILE_SIZE)
                    elif tile_value == 1:
                        self.tile_images['wall2'].draw(draw_x, draw_y, self.SCALED_TILE_SIZE, self.SCALED_TILE_SIZE)

                elif self.current_map_number == 3:
                    # 맵3: ground3만
                    self.tile_images['ground3'].draw(draw_x, draw_y, self.SCALED_TILE_SIZE, self.SCALED_TILE_SIZE)

    def draw(self, camera=None):
        """통합 렌더링"""
        if self.use_tilemap:
            # 타일맵 모드 (맵1, 2, 3)
            self.draw_tilemap(camera)
        else:
            # 기존 배경 모드 (맵4)
            self.draw_original_background(camera)